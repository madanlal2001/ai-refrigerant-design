# ==============================================================================
#  Build composition grid
# ==============================================================================
def build_comp_grid(step):
    """
    All (x1, x2) pairs for ternary sweep where x3 = 1 - x1 - x2 > 0.
    x1 and x2 each run from 0.1 to (0.9 - step) in increments of step.
    COMP_STEP is the gap between adjacent compositions, e.g.:
        0.4  → x vals [0.1, 0.5]             → 3 comps per triple
        0.2  → x vals [0.1, 0.3, 0.5, 0.7]  → 10 comps per triple
        0.1  → x vals [0.1, ..., 0.8]        → 36 comps per triple
    """
    vals = [round(0.1 + k * step, 6)
            for k in range(int(round(0.8 / step)) + 1)
            if round(0.1 + k * step, 6) < 1.0]
    return [(x1, x2) for x1 in vals for x2 in vals
            if round(x1 + x2, 6) <= 0.9]

# ==============================================================================
#  PR-EOS core (identical to binary sweep — works for n components)
# ==============================================================================
def pr_pure_params(T, Tc, Pc, omega):
    kappa = 0.37464 + 1.54226 * omega - 0.26992 * omega**2
    Tr    = T / Tc
    sq    = 1.0 + kappa * (1.0 - np.sqrt(Tr))
    alpha = sq * sq
    ac    = 0.45724 * R**2 * Tc**2 / Pc
    a     = ac * alpha
    b     = 0.07780 * R * Tc / Pc
    dadT  = ac * (-kappa * np.sqrt(alpha / (T * Tc)))
    return a, b, dadT


def mix_params(T, x, props, kij=0.0):
    n = len(x)
    a_i = np.empty(n); b_i = np.empty(n); da_i = np.empty(n)
    for k, (Tc, Pc, om) in enumerate(props):
        a_i[k], b_i[k], da_i[k] = pr_pure_params(T, Tc, Pc, om)
    a_mix = 0.0; dadT_mix = 0.0
    for i in range(n):
        for j in range(n):
            aij = np.sqrt(a_i[i] * a_i[j]) * (1.0 - kij)
            a_mix += x[i] * x[j] * aij
            if a_i[i] > 0 and a_i[j] > 0:
                daij = (1.0 - kij) * 0.5 * (da_i[i] * np.sqrt(a_i[j] / a_i[i]) +
                                             da_i[j] * np.sqrt(a_i[i] / a_i[j]))
            else:
                daij = 0.0
            dadT_mix += x[i] * x[j] * daij
    b_mix = float(np.dot(x, b_i))
    return a_mix, b_mix, dadT_mix, a_i, b_i


def compute_AB(T, P, a, b):
    return a * P / (R**2 * T**2), b * P / (R * T)


def solve_cubic_Z(A, B):
    coeffs = [1.0, -(1.0 - B), (A - 3.0 * B**2 - 2.0 * B),
              -(A * B - B**2 - B**3)]
    roots = np.roots(coeffs)
    real  = sorted([r.real for r in roots
                    if abs(r.imag) < 1e-8 and r.real > B], reverse=True)
    if len(real) >= 2: return real[0], real[-1]
    if len(real) == 1: return real[0], real[0]
    return None


def log_term(Z, B):
    num = Z + (1.0 + SQRT2) * B
    den = Z + (1.0 - SQRT2) * B
    if num <= 0 or den <= 0: return 0.0
    return np.log(num / den)

# ==============================================================================
#  Ideal-gas Cp integrals (a-e polynomial)
# ==============================================================================
def cp0_integ_H(cp, T, Tref):
    a, b, c, d, e = cp
    return (a*(T-Tref) + b/2*(T**2-Tref**2) + c/3*(T**3-Tref**3)
            + d/4*(T**4-Tref**4) + e/5*(T**5-Tref**5))


def cp0_integ_S(cp, T, Tref):
    a, b, c, d, e = cp
    return (a*np.log(T/Tref) + b*(T-Tref) + c/2*(T**2-Tref**2)
            + d/3*(T**3-Tref**3) + e/4*(T**4-Tref**4))

# ==============================================================================
#  Departure functions
# ==============================================================================
def H_dep(T, P, Z, a_mix, b_mix, dadT_mix):
    _, B = compute_AB(T, P, a_mix, b_mix)
    return R*T*(Z-1.0) + (T*dadT_mix-a_mix)/(2.0*SQRT2*b_mix)*log_term(Z, B)


def S_dep(T, P, Z, a_mix, b_mix, dadT_mix):
    _, B = compute_AB(T, P, a_mix, b_mix)
    return R*np.log(max(Z-B, 1e-15)) + dadT_mix/(2.0*SQRT2*b_mix)*log_term(Z, B)


def total_H(cps, x, T, P, Z, props, kij=0.0):
    a_mix, b_mix, dadT_mix, *_ = mix_params(T, x, props, kij)
    H_ig = sum(x[i]*cp0_integ_H(cps[i], T, T_REF) for i in range(len(x)))
    return H_ig + H_dep(T, P, Z, a_mix, b_mix, dadT_mix)


def total_S(cps, x, T, P, Z, props, kij=0.0):
    a_mix, b_mix, dadT_mix, *_ = mix_params(T, x, props, kij)
    S = 0.0
    for i in range(len(x)):
        s_i = cp0_integ_S(cps[i], T, T_REF) - R*np.log(P/P_REF)
        s_i += -R*np.log(x[i]) if x[i] > 0 else 0.0
        S += x[i] * s_i
    return S + S_dep(T, P, Z, a_mix, b_mix, dadT_mix)

# ==============================================================================
#  Saturation pressure — pseudo-pure model (fixed z=x=y throughout)
# ==============================================================================
_PSAT_CACHE = {}

def psat_pseudo(T, z, props, kij=0.0, tol=1e-8, max_iter=200):
    """
    Saturation pressure for fixed composition z (pseudo-pure model).
    Equal-fugacity condition on the cubic: ln_phi(ZV) = ln_phi(ZL).
    This is identical to the approach in bell_ternary.py / Bell (2019).
    """
    # Wilson init using pseudo-critical properties
    Tc_p = sum(z[i]*props[i][0] for i in range(len(z)))
    Pc_p = sum(z[i]*props[i][1] for i in range(len(z)))
    om_p = sum(z[i]*props[i][2] for i in range(len(z)))
    P = max(Pc_p * np.exp(5.373*(1.0+om_p)*(1.0-Tc_p/T)), 1e3)
    P = min(P, Pc_p * 2.0)

    for _ in range(max_iter):
        a_m, b_m, da_m, *_ = mix_params(T, z, props, kij)
        A, B = compute_AB(T, P, a_m, b_m)
        r = solve_cubic_Z(A, B)
        if r is None: return None
        ZV, ZL = r
        if ZV == ZL: return None   # single phase

        sqrt2 = SQRT2
        def ln_phi_pure(Z):
            lt = log_term(Z, B)
            return (Z-1.0) - np.log(max(Z-B,1e-15)) - A/(2*sqrt2*B)*lt

        lnfV = ln_phi_pure(ZV)
        lnfL = ln_phi_pure(ZL)
        if np.isnan(lnfV) or np.isnan(lnfL): return None

        delta = lnfL - lnfV
        Pn = P * np.exp(delta)
        if abs(Pn - P) / max(P, 1.0) < tol:
            return Pn
        P = Pn
        if P <= 0 or not np.isfinite(P) or P > 1e9: return None
    return P   # best estimate

# ==============================================================================
#  Isentropic outlet — Brent + two-phase wet compression
# ==============================================================================
def find_T2s(cps, S_target, z, P_cond, props, kij=0.0):
    """Isentropic compressor outlet at P_cond for composition z."""
    def S_vap(T):
        a_m, b_m, da_m, *_ = mix_params(T, z, props, kij)
        A, B = compute_AB(T, P_cond, a_m, b_m)
        r = solve_cubic_Z(A, B)
        if r is None: return None
        return total_S(cps, z, T, P_cond, r[0], props, kij)

    # Saturated-vapour entropy at T_cond
    S_sat = S_vap(T_COND)

    # Wet (two-phase) regime
    if S_sat is not None and S_target <= S_sat + 1e-9:
        a_m, b_m, da_m, *_ = mix_params(T_COND, z, props, kij)
        A, B = compute_AB(T_COND, P_cond, a_m, b_m)
        r = solve_cubic_Z(A, B)
        if r is None: return None
        ZV, ZL = r
        H_vap = total_H(cps, z, T_COND, P_cond, ZV, props, kij)
        H_liq = total_H(cps, z, T_COND, P_cond, ZL, props, kij)
        S_liq = total_S(cps, z, T_COND, P_cond, ZL, props, kij)
        dS = S_sat - S_liq
        x = (S_target - S_liq) / dS if abs(dS) > 1e-12 else 1.0
        x = min(max(x, 0.0), 1.0)
        H2s = H_liq + x*(H_vap - H_liq)
        return T_COND, H2s, "wet"

    # Superheated regime — Brent bracketing
    def resid(T):
        s = S_vap(T)
        return 1e9 if s is None else s - S_target

    T_lo, T_hi = T_COND, T_COND + 10.0
    f_lo = (S_sat - S_target) if S_sat is not None else -1.0
    f_hi = resid(T_hi)
    n = 0
    while f_lo * f_hi > 0.0 and n < 300:
        T_hi += 10.0
        if T_hi > 6.0 * max(p[0] for p in props): break
        f_hi = resid(T_hi); n += 1
    if f_lo * f_hi > 0.0: return None

    T2s = brentq(resid, T_lo, T_hi, xtol=1e-5, rtol=1e-10, maxiter=300)
    a_m, b_m, da_m, *_ = mix_params(T2s, z, props, kij)
    A, B = compute_AB(T2s, P_cond, a_m, b_m)
    r = solve_cubic_Z(A, B)
    if r is None: return None
    H2s = total_H(cps, z, T2s, P_cond, r[0], props, kij)
    return T2s, H2s, "superheated"

# ==============================================================================
#  Full ternary cycle (pseudo-pure, Bell convention)
# ==============================================================================
def compute_cycle_ternary(cps, z, props, kij=0.0):
    """
    COP for ternary mixture with feed composition z (pseudo-pure model).
    Bell convention: Psat at T_evap and T_cond, η=0.7.
    """
    z = np.asarray(z, dtype=float)
    z = z / z.sum()   # normalise

    P_evap = psat_pseudo(T_EVAP, z, props, kij)
    P_cond = psat_pseudo(T_COND, z, props, kij)
    if P_evap is None or P_cond is None:
        return None, "Psat failed"
    if P_cond <= P_evap:
        return None, "P_cond<=P_evap"
    if P_RATIO_MAX and (P_cond / P_evap) > P_RATIO_MAX:
        return None, "pressure ratio too high"

    # State 1: superheated vapour at evaporator outlet
    T1 = T_EVAP + DT_SH
    a1, b1, da1, *_ = mix_params(T1, z, props, kij)
    A1, B1 = compute_AB(T1, P_evap, a1, b1)
    r1 = solve_cubic_Z(A1, B1)
    if r1 is None: return None, "state1 cubic"
    H1 = total_H(cps, z, T1, P_evap, r1[0], props, kij)
    S1 = total_S(cps, z, T1, P_evap, r1[0], props, kij)

    # State 2s: isentropic compressor outlet
    out = find_T2s(cps, S1, z, P_cond, props, kij)
    if out is None: return None, "T2s failed"
    T2s, H2s, regime = out
    if T2S_MAX_K and T2s > T2S_MAX_K:
        return None, "T2s too high"
    H2 = H1 + (H2s - H1) / ETA_IS

    # State 3: subcooled liquid at condenser outlet
    T3 = T_COND - DT_SC
    a3, b3, da3, *_ = mix_params(T3, z, props, kij)
    A3, B3 = compute_AB(T3, P_cond, a3, b3)
    r3 = solve_cubic_Z(A3, B3)
    if r3 is None: return None, "state3 cubic"
    H3 = total_H(cps, z, T3, P_cond, r3[-1], props, kij)

    W = H2 - H1; Q = H1 - H3
    if W <= 0: return None, "W<=0"
    COP = Q / W
    if not np.isfinite(COP) or COP < COP_MIN or COP > COP_MAX:
        return None, "COP out of range"

    return {"COP": COP, "P_evap_bar": P_evap/1e5, "P_cond_bar": P_cond/1e5,
            "T2s_K": T2s, "regime": regime}, "OK"

# ==============================================================================
#  Pure-fluid baseline (for R-134a ratio)
# ==============================================================================
def pure_cop(mol):
    props = [(mol["Tc"], mol["Pc"], mol["omega"])]
    cps   = [mol["cp"]]
    z     = np.array([1.0])
    P_ev  = psat_pseudo(T_EVAP, z, props, KIJ)
    P_co  = psat_pseudo(T_COND, z, props, KIJ)
    if P_ev is None or P_co is None or P_co <= P_ev: return None
    T1 = T_EVAP + DT_SH
    a1, b1, da1, *_ = mix_params(T1, z, props, KIJ)
    A1, B1 = compute_AB(T1, P_ev, a1, b1); r1 = solve_cubic_Z(A1, B1)
    if r1 is None: return None
    H1 = total_H(cps, z, T1, P_ev, r1[0], props, KIJ)
    S1 = total_S(cps, z, T1, P_ev, r1[0], props, KIJ)
    out = find_T2s(cps, S1, z, P_co, props, KIJ)
    if out is None: return None
    _, H2s, _ = out
    H2 = H1 + (H2s - H1) / ETA_IS
    T3 = T_COND - DT_SC
    a3, b3, da3, *_ = mix_params(T3, z, props, KIJ)
    A3, B3 = compute_AB(T3, P_co, a3, b3); r3 = solve_cubic_Z(A3, B3)
    if r3 is None: return None
    H3 = total_H(cps, z, T3, P_co, r3[-1], props, KIJ)
    W = H2 - H1
    return (H1 - H3) / W if W > 0 else None

# ==============================================================================
#  Data loading (reuse binary sweep logic)
# ==============================================================================
def load_molecules():
    props = (pd.read_csv(PROPS_FILE) if PROPS_FILE.endswith(".csv")
             else pd.read_excel(PROPS_FILE))
    cp    = (pd.read_excel(CP_FILE) if CP_FILE.endswith((".xlsx",".xls"))
             else pd.read_csv(CP_FILE))
    for d in (props, cp):
        d[COL_NAME] = d[COL_NAME].astype(str).str.strip()
    m = pd.merge(props[[COL_NAME,COL_TC,COL_PC,COL_OMEGA]].dropna(subset=[COL_NAME]),
                 cp[[COL_NAME]+CP_COLS].dropna(subset=[COL_NAME]),
                 on=COL_NAME, how="inner")
    m = m.drop_duplicates(subset=COL_NAME, keep="first")
    before = len(m)
    m = m.dropna(subset=[COL_TC,COL_PC,COL_OMEGA]+CP_COLS)
    dropped_inc = before - len(m)
    dropped_bl = 0
    if DROP_BLENDS:
        mask = m[COL_NAME].str.contains("mixture|blend", case=False, na=False)
        dropped_bl = int(mask.sum()); m = m[~mask]
    dropped_tc = 0
    if MIN_COMPONENT_TC:
        mask = m[COL_TC].astype(float) <= MIN_COMPONENT_TC
        dropped_tc = int(mask.sum()); m = m[~mask]
    pc_scale = 1e5 if PC_UNIT.lower() == "bar" else 1.0
    mols = []
    for _, r in m.iterrows():
        mols.append({"name": r[COL_NAME], "Tc": float(r[COL_TC]),
                     "Pc": float(r[COL_PC])*pc_scale, "omega": float(r[COL_OMEGA]),
                     "cp": tuple(float(r[c]) for c in CP_COLS)})
    return mols, dropped_inc, dropped_bl, dropped_tc

# ==============================================================================
#  Worker — processes a chunk of triples
# ==============================================================================
def _worker(args):
    triple_slice, comp_grid, cop_r134a, kij = args
    rows = []; skip = Counter(); n_wet = 0
    for A, B, C in triple_slice:
        props = [(A["Tc"],A["Pc"],A["omega"]),
                 (B["Tc"],B["Pc"],B["omega"]),
                 (C["Tc"],C["Pc"],C["omega"])]
        cps   = [A["cp"], B["cp"], C["cp"]]
        for x1, x2 in comp_grid:
            x3 = round(1.0 - x1 - x2, 6)
            if x3 <= 0: continue
            z  = [x1, x2, x3]
            try:
                state, status = compute_cycle_ternary(cps, z, props, kij)
            except Exception as e:
                state, status = None, f"err:{type(e).__name__}"
            if state is None:
                skip[status] += 1; continue
            if state["regime"] == "wet": n_wet += 1
            rows.append({
                "Component1": A["name"], "Component2": B["name"], "Component3": C["name"],
                "x1": x1, "x2": x2, "x3": round(x3, 6),
                "COP": round(state["COP"], 5),
                "COP_ratio_vs_R134a": round(state["COP"]/cop_r134a, 5) if cop_r134a else None,
                "regime":      state["regime"],
                "P_evap_bar":  round(state["P_evap_bar"], 4),
                "P_cond_bar":  round(state["P_cond_bar"], 4),
                "T2s_K":       round(state["T2s_K"], 2),
            })
    return rows, skip, n_wet

# ==============================================================================
#  Main
# ==============================================================================
def main():
    print("=" * 78)
    print("  PR-EOS Ternary Mixture — COP Sweep  (Bell et al. 2019 convention)")
    print(f"  T_evap={T_EVAP_C}°C  T_cond={T_COND_C}°C  dTsh={DT_SH}K"
          f"  dTsc={DT_SC}K  η={ETA_IS}  kij={KIJ}")
    print(f"  Composition step : {COMP_STEP}")
    print("=" * 78)

    mols, drop_inc, drop_bl, drop_tc = load_molecules()
    print(f"\n  Usable molecules : {len(mols)}"
          f"  (dropped {drop_inc} incomplete, {drop_bl} blends,"
          f" {drop_tc} Tc≤{MIN_COMPONENT_TC:.0f}K)")

    # R-134a baseline
    cop_r134a = None
    if R134A_NAME:
        base = next((m for m in mols
                     if m["name"].strip().lower()==R134A_NAME.strip().lower()), None)
        if base:
            cop_r134a = pure_cop(base)
        print(f"  R-134a baseline COP : {cop_r134a:.4f}" if cop_r134a
              else "  R-134a baseline : not found")

    # Build triple list and composition grid
    all_triples = list(itertools.combinations(mols, 3))
    comp_grid   = build_comp_grid(COMP_STEP)
    total = len(all_triples) * len(comp_grid)
    n_workers = N_WORKERS or os.cpu_count() or 1

    print(f"  Unique triples   : {len(all_triples):,}")
    print(f"  Compositions/triple : {len(comp_grid)}  {comp_grid[:4]}...")
    print(f"  Total calcs      : {len(all_triples):,} × {len(comp_grid)} = {total:,}")
    print(f"  CPU workers      : {n_workers}")
    print(f"  Est. time        : ~{total/20/n_workers/3600:.1f} h\n")

    # Split into chunks
    chunk_size = max(1, len(all_triples) // n_workers)
    chunks = [all_triples[k:k+chunk_size]
              for k in range(0, len(all_triples), chunk_size)]
    work = [(chunk, comp_grid, cop_r134a, KIJ) for chunk in chunks]

    t0 = time.time()
    if n_workers == 1:
        results = [_worker(w) for w in work]
    else:
        ctx = mp.get_context("spawn")
        with ctx.Pool(processes=n_workers) as pool:
            results = pool.map(_worker, work)

    # Merge
    all_rows = []; skip = Counter(); n_wet = 0
    for rows, sk, w in results:
        all_rows.extend(rows); skip.update(sk); n_wet += w

    df = pd.DataFrame(all_rows)
    df.to_csv(OUTPUT_FILE, index=False)

    n_skip = sum(skip.values())
    summ = pd.DataFrame(sorted(skip.items(), key=lambda kv: -kv[1]),
                        columns=["skip_reason", "count"])
    summ.to_csv(SKIP_FILE, index=False)

    elapsed = time.time() - t0
    print("\n" + "=" * 78)
    print(f"  Done in {elapsed/60:.1f} min   ({n_workers} worker(s))")
    print(f"  Total attempted  : {total:,}")
    print(f"  Clean rows (COP) : {len(df):,}")
    print(f"  Skipped          : {n_skip:,}  ({100*n_skip/total:.1f}%" if total > 0 else f"  Skipped          : {n_skip:,}")
    if len(df):
        print(f"  COP range        : {df['COP'].min():.3f} – {df['COP'].max():.3f}"
              f"   (median {df['COP'].median():.3f})")
        print(f"  Wet-compression  : {n_wet:,}")
    print("\n  Skip reasons:")
    for reason, c in summ.itertuples(index=False):
        print(f"    {c:>8,}  {reason}")
    print(f"\n  Saved → {OUTPUT_FILE}")
    print(f"  Saved → {SKIP_FILE}")
    print("=" * 78)
    return df


