def coolprop_cop(cp_name1, cp_name2, x1):
    """CoolProp COP in the SAME Bell-mode convention (dew@evap, bubble@cond)."""
    try:
        import CoolProp.CoolProp as CP
        s = f"{cp_name1}[{x1}]&{cp_name2}[{1.0 - x1}]"
        P_evap = CP.PropsSI("P", "T", T_EVAP, "Q", 1, s)   # dew @ T_evap
        P_cond = CP.PropsSI("P", "T", T_COND, "Q", 0, s)   # bubble @ T_cond
        if P_cond <= P_evap:
            return None
        T1 = T_EVAP + DT_SH
        H1 = CP.PropsSI("H", "T", T1, "P", P_evap, s)
        S1 = CP.PropsSI("S", "T", T1, "P", P_evap, s)
        lo, hi = T_COND, T_COND + 250.0
        for _ in range(80):
            mid = 0.5 * (lo + hi)
            if CP.PropsSI("S", "T", mid, "P", P_cond, s) < S1:
                lo = mid
            else:
                hi = mid
        H2s = CP.PropsSI("H", "T", 0.5 * (lo + hi), "P", P_cond, s)
        H2 = H1 + (H2s - H1) / ETA_IS
        H3 = CP.PropsSI("H", "T", T_COND - DT_SC, "P", P_cond, s)
        cop = (H1 - H3) / (H2 - H1)
        return cop if 0 < cop < 100 else None
    except Exception:
        return None

# ==============================================================================
#  Data loading
# ==============================================================================
def load_molecules():
    props = pd.read_csv(PROPS_FILE) if PROPS_FILE.lower().endswith(".csv") \
        else pd.read_excel(PROPS_FILE)
    cp = pd.read_excel(CP_FILE) if CP_FILE.lower().endswith((".xlsx", ".xls")) \
        else pd.read_csv(CP_FILE)
    for d in (props, cp):
        d[COL_NAME] = d[COL_NAME].astype(str).str.strip()
    keep_cp = [COL_NAME] + CP_COLS + ([COL_CP_NAME] if (COMPARE_COOLPROP and COL_CP_NAME in cp) else [])
    m = pd.merge(props[[COL_NAME, COL_TC, COL_PC, COL_OMEGA]].dropna(subset=[COL_NAME]),
                 cp[keep_cp].dropna(subset=[COL_NAME]), on=COL_NAME, how="inner")
    m = m.drop_duplicates(subset=COL_NAME, keep="first")

    before = len(m)
    m = m.dropna(subset=[COL_TC, COL_PC, COL_OMEGA] + CP_COLS)
    dropped_incomplete = before - len(m)

    dropped_blends = 0
    if DROP_BLENDS:
        mask = m[COL_NAME].str.contains("mixture|blend", case=False, na=False)
        dropped_blends = int(mask.sum())
        m = m[~mask]

    dropped_lowtc = 0
    if MIN_COMPONENT_TC and MIN_COMPONENT_TC > 0:
        mask = m[COL_TC].astype(float) <= MIN_COMPONENT_TC
        dropped_lowtc = int(mask.sum())
        m = m[~mask]

    pc_scale = 1e5 if PC_UNIT.lower() == "bar" else 1.0
    mols = []
    for _, r in m.iterrows():
        mols.append({
            "name": r[COL_NAME],
            "Tc": float(r[COL_TC]),
            "Pc": float(r[COL_PC]) * pc_scale,
            "omega": float(r[COL_OMEGA]),
            "cp": tuple(float(r[c]) for c in CP_COLS),
            "cp_name": (str(r[COL_CP_NAME]) if (COMPARE_COOLPROP and COL_CP_NAME in m) else None),
        })
    return mols, dropped_incomplete, dropped_blends, dropped_lowtc

# ==============================================================================
#  Pure-fluid baseline COP (for the R-134a ratio)
# ==============================================================================
def pure_cop(mol):
    """
    Bell-mode COP of a single pure fluid (R-134a baseline).
    For a pure fluid dew pressure = bubble pressure = Psat, so we use
    bubble_point_P at both temperatures (dew_point_P degenerates at n=1).
    """
    props = [(mol["Tc"], mol["Pc"], mol["omega"])]
    cps = [mol["cp"]]
    P_evap, _ = bubble_point_P(T_EVAP, [1.0], props, KIJ)
    P_cond, _ = bubble_point_P(T_COND, [1.0], props, KIJ)
    if P_evap is None or P_cond is None or P_cond <= P_evap:
        return None
    T1 = T_EVAP + DT_SH
    a1, b1, _, *_ = mix_params(T1, [1.0], props, KIJ)
    A1, B1 = compute_AB(T1, P_evap, a1, b1); r1 = solve_cubic_Z(A1, B1)
    if r1 is None:
        return None
    H1 = total_H(cps, [1.0], T1, P_evap, r1[0], props, KIJ)
    S1 = total_S(cps, [1.0], T1, P_evap, r1[0], props, KIJ)
    out = find_T2s_mix(cps, S1, [1.0], P_cond, props, KIJ)
    if out is None:
        return None
    _, H2s, _ = out
    H2 = H1 + (H2s - H1) / ETA_IS
    T3 = T_COND - DT_SC
    a3, b3, _, *_ = mix_params(T3, [1.0], props, KIJ)
    A3, B3 = compute_AB(T3, P_cond, a3, b3); r3 = solve_cubic_Z(A3, B3)
    if r3 is None:
        return None
    H3 = total_H(cps, [1.0], T3, P_cond, r3[-1], props, KIJ)
    W = H2 - H1
    return (H1 - H3) / W if W > 0 else None

# ==============================================================================
#  Worker  — runs a chunk of pairs in one process
# ==============================================================================
def _worker(args):
    """
    Process a slice of pairs independently.  Each worker gets a plain list of
    (molA, molB) dicts so no shared state is needed — safe for multiprocessing.
    Returns (rows_list, skip_counter, n_wet).
    """
    pair_slice, x1_list, cop_r134a, kij = args
    rows = []; skip = Counter(); n_wet = 0
    for A, Bm in pair_slice:
        props = [(A["Tc"], A["Pc"], A["omega"]), (Bm["Tc"], Bm["Pc"], Bm["omega"])]
        cps   = [A["cp"], Bm["cp"]]
        for x1 in x1_list:
            x2 = round(1.0 - x1, 2)
            try:
                state, status = compute_cycle_mixture(cps, [x1, x2], props, kij)
            except Exception as e:
                state, status = None, f"err:{type(e).__name__}"
            if state is None:
                skip[status] += 1
                continue
            if state["regime"] == "wet":
                n_wet += 1
            rows.append({
                "Component1": A["name"], "Component2": Bm["name"],
                "x1": x1, "x2": x2,
                "COP": round(state["COP"], 5),
                "COP_ratio_vs_R134a": (round(state["COP"] / cop_r134a, 5)
                                       if cop_r134a else None),
                "regime":      state["regime"],
                "P_evap_bar":  round(state["P_evap_bar"], 4),
                "P_cond_bar":  round(state["P_cond_bar"], 4),
                "T2s_K":       round(state["T2s_K"], 2),
            })
    return rows, skip, n_wet


# ==============================================================================
#  Main sweep
# ==============================================================================
def main():
    print("=" * 78)
    print("  PR-EOS Binary Mixture — COP Sweep  (Bell et al. 2019 convention)")
    print(f"  T_evap={T_EVAP_C}°C  T_cond={T_COND_C}°C  dTsh={DT_SH}K  dTsc={DT_SC}K"
          f"  η={ETA_IS}  kij={KIJ}")
    print(f"  Compositions: x1 = {X1_LIST[0]}…{X1_LIST[-1]}"
          f"  step={round(X1_LIST[1]-X1_LIST[0],2)}  ({len(X1_LIST)} points)")
    print("=" * 78)

    mols, drop_inc, drop_bl, drop_tc = load_molecules()
    print(f"\n  Usable molecules : {len(mols)}"
          f"  (dropped {drop_inc} incomplete, {drop_bl} blends,"
          f" {drop_tc} with Tc≤{MIN_COMPONENT_TC:.1f} K)")

    # --- R-134a baseline COP (Bell-mode) for the ratio column ------------------
    cop_r134a = None
    if R134A_NAME:
        base = next((m for m in mols
                     if m["name"].strip().lower() == R134A_NAME.strip().lower()), None)
        if base is not None:
            cop_r134a = pure_cop(base)
        if cop_r134a:
            print(f"  R-134a baseline COP (PR, Bell-mode) : {cop_r134a:.4f}")
        else:
            print("  R-134a baseline : not found in molecule list")

    # --- Build pair list --------------------------------------------------------
    all_pairs = [(mols[i], mols[j])
                 for i in range(len(mols)) for j in range(i + 1, len(mols))]
    total = len(all_pairs) * len(X1_LIST)
    n_workers = N_WORKERS or os.cpu_count() or 1
    print(f"  Unique pairs     : {len(all_pairs)}")
    print(f"  Total calcs      : {len(all_pairs)} × {len(X1_LIST)} = {total}")
    print(f"  CPU workers      : {n_workers}\n")

    # --- Split pairs into chunks (one per worker) -------------------------------
    chunk_size = max(1, len(all_pairs) // n_workers)
    chunks = [all_pairs[k:k + chunk_size]
              for k in range(0, len(all_pairs), chunk_size)]
    work = [(chunk, X1_LIST, cop_r134a, KIJ) for chunk in chunks]

    # --- Dispatch ---------------------------------------------------------------
    t0 = time.time()
    if n_workers == 1:
        # Single-process path — useful for debugging and Windows fallback.
        results = [_worker(w) for w in work]
    else:
        # 'spawn' context avoids issues with numpy/fork on Linux and macOS.
        ctx = mp.get_context("spawn")
        with ctx.Pool(processes=n_workers) as pool:
            results = pool.map(_worker, work)

    # --- Merge results ----------------------------------------------------------
    all_rows = []; skip = Counter(); n_wet = 0
    for rows, sk, w in results:
        all_rows.extend(rows); skip.update(sk); n_wet += w

    # --- Save CLEAN CSV (computed rows only, no NaN rows) ----------------------
    df = pd.DataFrame(all_rows)
    df.to_csv(OUTPUT_FILE, index=False)

    # --- Skip summary -----------------------------------------------------------
    n_skip = sum(skip.values())
    summ = pd.DataFrame(sorted(skip.items(), key=lambda kv: -kv[1]),
                        columns=["skip_reason", "count"])
    summ.to_csv("binary_mixture_skip_summary.csv", index=False)

    elapsed = time.time() - t0
    print("\n" + "=" * 78)
    print(f"  Done in {elapsed/60:.1f} min   ({n_workers} worker(s))")
    print(f"  Total attempted  : {total}")
    print(f"  Clean rows (COP) : {len(df)}")
    print(f"  Skipped          : {n_skip}  ({100*n_skip/total:.1f}%)")
    if len(df):
        print(f"  COP range        : {df['COP'].min():.3f} – {df['COP'].max():.3f}"
              f"   (median {df['COP'].median():.3f})")
        print(f"  Wet-compression  : {n_wet}")
    if cop_r134a:
        print(f"  R-134a baseline  : {cop_r134a:.4f}"
              f"  (ratio column = COP / {cop_r134a:.4f})")
    print("\n  Skip reasons:")
    for reason, c in summ.itertuples(index=False):
        print(f"    {c:>8}  {reason}")
    print(f"\n  Saved → {OUTPUT_FILE}")
    print(f"  Saved → binary_mixture_skip_summary.csv")
    print("=" * 78)
    return df


if __name__ == "__main__":
    main()